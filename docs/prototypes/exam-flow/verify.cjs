const assert = require('node:assert/strict');
const fs = require('node:fs');
const { createHash } = require('node:crypto');
const path = require('node:path');
const { createRequire } = require('node:module');

const root = path.resolve(__dirname, '../../..');
const webRequire = createRequire(path.join(process.env.EXAM_FLOW_WEB_ROOT || path.join(root, 'web'), 'package.json'));
const { chromium } = webRequire('playwright');
const base = process.env.EXAM_FLOW_URL || 'http://127.0.0.1:8765/docs/prototypes/exam-flow/index.html';
const output = path.resolve(process.env.EXAM_FLOW_EVIDENCE_DIR || '/private/tmp/exam-flow-evidence');

(async () => {
  const browser = await chromium.launch({ headless: true });
  const passed = [], screenshots = [], errors = [], externalRequests = [];
  let counter = 0;
  fs.mkdirSync(output, { recursive: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1713, height: 1034 } });
    page.on('pageerror', error => errors.push(String(error)));
    page.on('request', request => { if (new URL(request.url()).origin !== new URL(base).origin) externalRequests.push(request.url()); });
    const click = action => page.locator(`[data-action="${action}"]`).first().click();
    const contains = async (selector, value) => assert((await page.locator(selector).innerText()).includes(value), `${selector}: ${value}`);
    const save = () => page.locator('#settings-form button[type="submit"]').click();
    const overview = () => page.locator('[data-action="tab"][data-value="overview"]').click();
    const load = async (hash = '', access = 'ready') => {
      const url = new URL(base);
      url.hash = hash;
      url.searchParams.set('verification', String(++counter));
      url.searchParams.set('access', access);
      await page.goto(url.href);
      await page.evaluate(() => document.fonts.ready);
    };
    const capture = async (name, selector) => {
      await page.evaluate(() => window.scrollTo(0, 0));
      const options = { path: path.join(output, name), animations: 'disabled' };
      if (selector) await page.locator(selector).screenshot(options);
      else await page.screenshot({ ...options, fullPage: true });
      screenshots.push(name);
    };
    const limit = () => page.getByText('Maksimal percobaan', { exact: true }).evaluate(el => el.nextElementSibling.textContent);
    const geometry = async label => assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${label}: overflow`);

    await load();
    assert(!(await page.locator('#app').innerText()).match(/\bDraft\b|\bPublished\b/));
    assert.equal(await page.locator('#status-filter').count(), 0);
    assert.equal(await page.locator('.admin-table th').count(), 5);
    assert.equal(await page.locator('.page-head .title-icon').evaluate(el => el.getBoundingClientRect().width), 64);
    await capture('admin-list-desktop.png');
    await page.locator('#exam-search').fill('sebelumnya');
    await contains('#exam-count', '1 ujian');
    await page.locator('#exam-search').fill('tidak-ada');
    assert(await page.locator('#empty-search').isVisible());
    await click('clear-exam-search');
    await contains('#exam-count', '2 ujian');
    await click('legacy-detail');
    await contains('#app', 'format sebelumnya');
    passed.push('admin list: standard header/table, no exam status, search/reset/empty, legacy notice');

    await load('admin-overview');
    assert.equal(await page.locator('[data-action="settings"]').count(), 1);
    assert.equal(await page.locator('[data-action="preview"]').count(), 1);
    const labels = await page.locator('.admin-overview-info dt').allTextContents();
    assert(!labels.some(label => ['Judul', 'Navigasi section', 'Waktu pengerjaan', 'Jendela check-in', 'Rilis hasil'].includes(label)));
    await capture('admin-overview-desktop.png');
    await click('settings');
    assert(!(await page.locator('[name="multiple_attempts"]').isChecked()));
    assert(!(await page.locator('#attempts-field').isVisible()));
    await page.locator('[name="multiple_attempts"]').check();
    await page.locator('[name="attempts"]').fill('');
    assert(!(await page.locator('[name="attempts"]').evaluate(el => el.checkValidity())));
    await page.locator('[name="attempts"]').fill('3');
    await save();
    assert.equal(await limit(), '3 kali');
    await click('settings');
    await page.locator('[name="unlimited_attempts"]').check();
    await save();
    assert.equal(await limit(), 'Tanpa batas');
    await click('settings');
    assert(await page.locator('[name="unlimited_attempts"]').isChecked());
    await page.locator('[name="multiple_attempts"]').uncheck();
    await save();
    assert.equal(await limit(), '1 kali');
    await page.locator('#scenario').selectOption('locked');
    await click('settings');
    assert(await page.locator('[name="timer"]').first().isDisabled());
    assert(await page.locator('[name="whatsapp_url"]').isEnabled());
    await click('close');
    passed.push('admin overview: no duplicate fields/actions; attempts finite/unlimited/off; policy lock');

    await load('admin-detail');
    await page.locator('[data-presentation="literasi"]').selectOption('all_on_page');
    assert(await page.locator('[data-action="save-sections"]').isDisabled());
    await contains('[role="alert"] >> nth=0', 'Materi soal 2');
    await click('fix-presentation');
    await click('library');
    await page.locator('#add-english').check();
    await page.locator('#library-form button[type="submit"]').click();
    await page.locator('[data-action="up"][data-id="english"]').click();
    assert(await page.locator('[data-action="preview"]').isDisabled());
    await click('save-sections');
    assert.equal(await page.locator('.section-item').count(), 3);
    await page.locator('[data-action="remove"][data-id="english"]').click();
    await click('save-sections');
    await click('settings');
    await page.locator('[name="navigation"][value="free"]').check();
    await save();
    await contains('#settings-error', 'memerlukan navigasi berurutan');
    await click('close');
    passed.push('section composition: material conflict/fix, add/reorder/remove, save barrier, invalid policy');

    await load('admin-detail');
    await click('preview');
    assert.equal(await page.locator('.exam-community').count(), 0);
    await page.locator('[data-go="admin"]').click();
    await click('admin-detail');
    await click('settings');
    await page.locator('[name="whatsapp_url"]').fill('https://example.com/group');
    await save();
    await contains('#settings-error', 'link undangan grup WhatsApp');
    const sampleLink = 'https://chat.whatsapp.com/PrototypeOnlyNotARealGroup';
    await page.locator('[name="whatsapp_url"]').fill(sampleLink);
    await save();
    await click('preview');
    const headings = await page.locator('.student-detail>section').evaluateAll(nodes => nodes.map(node => node.querySelector('h2')?.textContent));
    assert.deepEqual(headings.slice(0, 3), ['Informasi ujian', 'Grup WhatsApp kompetisi', 'Cara mengerjakan']);
    const link = page.getByRole('link', { name: 'Gabung grup WhatsApp (tab baru)' });
    assert.equal(await link.getAttribute('href'), sampleLink);
    assert.equal(await link.getAttribute('target'), '_blank');
    await capture('student-whatsapp-desktop.png', '.exam-community');
    await page.locator('#ready').check();
    assert(await page.locator('[data-action="start"]').isEnabled());
    passed.push('WhatsApp: optional, domain validation, configured block placement, destination, no join required');

    await load('student-list', 'upcoming');
    await contains('.student-card', 'Belum dibuka');
    await contains('.exam-card-footer', 'Dibuka dalam 5 hari');
    await capture('student-upcoming-card.png', '.student-card');
    await click('student-detail');
    assert(await page.locator('[data-action="start"]').isDisabled());
    await page.evaluate(() => { startDialog(); startSession(); });
    assert(await page.evaluate(() => session === null));
    await capture('student-information-desktop.png', '.exam-information');
    await page.locator('#student-scenario').selectOption('ready');
    await page.locator('#ready').check();
    await click('start');
    assert(await page.locator('#modal').isVisible());
    await click('start-confirm');
    await page.locator('[data-answer="l1"][value="0"]').check();
    await click('next');
    await contains('.question-card', 'Materi soal 2');
    assert.equal(await page.locator('.question-inner>.material').count(), 0);
    await click('next');
    await click('finish');
    await contains('#modal', '2 soal belum dijawab');
    await click('confirm-finish');
    assert.equal(await page.locator('.question-card').count(), 3);
    await page.locator('[data-answer="m1"][value="3"]').check();
    await click('finish');
    await contains('#modal', '4 soal belum dijawab');
    await click('confirm-finish');
    await contains('#app', 'Hasil belum ditampilkan');
    passed.push('student upcoming/preflight and sequential runtime: own/shared material, both presentations, blanks, submit');

    const viewports = [1713, 1440, 1200, 1024, 768, 390, 360];
    for (const width of viewports) {
      await page.setViewportSize({ width, height: 1034 });
      await load(); await geometry(`admin list ${width}`);
      await load('admin-overview'); await geometry(`admin overview ${width}`);
      await load('student-detail', 'upcoming'); await geometry(`student detail ${width}`);
      const clipped = await page.locator('.exam-information').evaluate(el => [...el.querySelectorAll('h2,h3,p,dt,dd')].filter(node => node.scrollWidth > node.clientWidth + 1).map(node => node.textContent));
      assert.deepEqual(clipped, []);
      if (width === 390) await capture('student-detail-mobile.png');
    }
    passed.push('responsive admin list/overview and student detail at seven viewport widths');
    assert.deepEqual(errors, []);
    assert.deepEqual(externalRequests, []);
    const sources = Object.fromEntries(['index.html', 'style.css', 'app.js', 'verify.cjs'].map(name => [name, createHash('sha256').update(fs.readFileSync(path.join(__dirname, name))).digest('hex')]));
    const report = { scope: 'static prototype only; no production/API/database verification', verified_at: new Date().toISOString(), passed, viewports, screenshots, sources, errors, external_requests: externalRequests };
    fs.writeFileSync(path.join(output, 'report.json'), JSON.stringify(report, null, 2) + '\n');
    process.stdout.write(JSON.stringify(report, null, 2) + '\n');
  } finally {
    await browser.close();
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
